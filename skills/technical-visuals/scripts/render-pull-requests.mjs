// Regenerate local previews with GitHub's Markdown renderer. Requires authenticated gh.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
const directory = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../examples/pull-requests",
);
const examples = {};
for (const key of ["cache", "retry", "queue"]) {
  const markdown = fs.readFileSync(path.join(directory, key + ".md"), "utf8");
  const html = execFileSync("gh", ["api", "markdown", "--input", "-"], {
    input: JSON.stringify({ text: markdown, mode: "gfm" }),
    encoding: "utf8",
  });
  examples[key] = { markdown, html };
}
fs.writeFileSync(
  path.join(directory, "rendered.js"),
  "// Generated by scripts/render-pull-requests.mjs; edit the .md sources.\nwindow.prExamples = " +
    JSON.stringify(examples, null, 2) +
    ";\n",
);
